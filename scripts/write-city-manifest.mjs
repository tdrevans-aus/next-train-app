/**
 * Write public/city-manifest.seed.json from the registry — the bundled fallback the client
 * uses on a fresh install with no network (docs/jim-brief-registry-driven-client.md).
 * Same builder as api/cities.js/dev-server.js's /api/cities route
 * (lib/cities/city-manifest.js), so the seed can never drift from what the live endpoint
 * would return for the current registry state. Wired into `npm run cap:sync` and the
 * "Write city-directions JSON" CI workflow — re-run this whenever a city flips or its
 * bounds/country/directions change.
 *
 * Usage: node scripts/write-city-manifest.mjs
 */
import { writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
import { buildCityManifest } from "../lib/cities/city-manifest.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_FILE = join(ROOT, "public", "city-manifest.seed.json");
// Synchronous companion to the JSON seed (docs/jim-brief-registry-driven-client.md follow-up,
// same day): public/city-manifest.js needs a manifest available at parse time, with zero
// async wait, so classic-script callers that run before any fetch could possibly resolve
// (VM-sandboxed QA scripts with no network at all, or a real page's very first tick) still
// see every live city — matching the old hardcoded-list behaviour that never had a "not
// loaded yet" state. The plain .json file stays the documented network-blocked fallback
// fetch target and the artifact qa/live-city-lists-sync.mjs diffs against; this .js file is
// generated from the exact same buildCityManifest() call so the two can never drift.
const OUT_JS_FILE = join(ROOT, "public", "city-manifest.seed.js");

export function writeCityManifestSeed(outFile = OUT_FILE, outJsFile = OUT_JS_FILE) {
  const manifest = buildCityManifest();
  const json = JSON.stringify(manifest, null, 2);
  writeFileSync(outFile, `${json}\n`);
  writeFileSync(
    outJsFile,
    `// Generated by scripts/write-city-manifest.mjs — do not hand-edit.\n` +
      `// eslint-disable-next-line no-restricted-globals\n` +
      `window.__CITY_MANIFEST_SEED__ = ${json};\n`
  );
  return manifest;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const manifest = writeCityManifestSeed();
  console.log(
    `write-city-manifest: wrote ${manifest.cities.length} cities, ${manifest.countries.length} countries to ${OUT_FILE} and ${OUT_JS_FILE}`
  );
}
