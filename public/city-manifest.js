/**
 * City manifest client — loads "which cities exist" from the server instead of the client
 * bundling it (docs/jim-brief-registry-driven-client.md). Replaces the seven hand-maintained
 * copies (public/city-session.js's MULTI_CITY_IDS/COUNTRIES/CITY_BOUNDS, public/app.js's
 * LIVE_CITY_IDS/NEARBY_MULTI_CITY_IDS, public/journey-model.js's
 * PERSISTED_CITY_IDS/PERSISTED_COUNTRY_IDS, public/brisbane-dogfood.js's MULTI_CITY_IDS) with
 * accessors over one loaded manifest, so a new live city appears within the 5-minute
 * /api/cities cache instead of needing an app release.
 *
 * Resolution order on boot: fresh network (/api/cities) -> cached copy from localStorage
 * (any age; a console warning only past 7 days old) -> bundled seed
 * (city-manifest.seed.json, generated by scripts/write-city-manifest.mjs). A successful
 * network fetch always wins and re-caches. Every accessor reads the CURRENT best-known
 * manifest, so callers made before the network fetch resolves still get a usable (cache or
 * seed) answer rather than an empty one — there's no "not ready yet" state to handle.
 *
 * Must load before public/brisbane-dogfood.js, public/city-session.js, public/journey-model.js
 * and public/app.js (see public/index.html's script order) — those all read window.CityManifest.
 */
(function () {
  "use strict";

  const STORAGE_KEY = "nextTrainCityManifest";
  const SEED_URL = "/city-manifest.seed.json";
  const NETWORK_URL = "/api/cities";
  const STALE_WARN_MS = 7 * 24 * 60 * 60 * 1000;

  function emptyManifest() {
    return { contractVersion: 2, cities: [], countries: [], docs: "" };
  }

  function normalizeManifest(raw) {
    if (!raw || !Array.isArray(raw.cities)) {
      return null;
    }
    return {
      contractVersion: raw.contractVersion ?? 2,
      cities: raw.cities,
      countries: Array.isArray(raw.countries) ? raw.countries : [],
      docs: raw.docs || "",
    };
  }

  let manifest = emptyManifest();
  let source = "empty";

  /** Never regress to an empty/broken manifest — only apply a normalizable, non-empty one. */
  function applyManifest(raw, nextSource) {
    const normalized = normalizeManifest(raw);
    if (!normalized || normalized.cities.length === 0) {
      return false;
    }
    manifest = normalized;
    source = nextSource;
    return true;
  }

  // Embedded seed (public/city-manifest.seed.js, generated by scripts/write-city-manifest.mjs
  // alongside the plain .json — loaded via a <script> tag immediately before this one, see
  // index.html) applies FIRST and synchronously, with zero async wait — every classic-script
  // caller of window.CityManifest, including one that runs before any fetch could possibly
  // resolve, sees every live city from the moment this file finishes parsing. Resolution
  // priority is still network > cache > seed (cache/network below only ever *replace* this,
  // matching the old always-available hardcoded-list behaviour this replaces).
  applyManifest(window.__CITY_MANIFEST_SEED__, "seed");

  function readCache() {
    try {
      const raw = localStorage.getItem(STORAGE_KEY);
      if (!raw) return null;
      return JSON.parse(raw);
    } catch {
      return null;
    }
  }

  function writeCache(raw) {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify({ fetchedAt: Date.now(), manifest: raw }));
    } catch {
      /* storage full/unavailable — this session just stays network/seed-driven */
    }
  }

  const cached = readCache();
  if (cached && applyManifest(cached.manifest, "cache")) {
    const ageMs = Date.now() - (Number(cached.fetchedAt) || 0);
    if (ageMs > STALE_WARN_MS) {
      console.warn(
        `[city-manifest] cached manifest is ${Math.round(ageMs / (24 * 60 * 60 * 1000))} day(s) old — cities may be stale`
      );
    }
  }

  function fetchJson(url) {
    return fetch(url, { cache: "no-store" }).then((response) => {
      if (!response.ok) {
        throw new Error(`HTTP ${response.status}`);
      }
      return response.json();
    });
  }

  /** ?fixture=<name> (TESTING.md — dev server only, never honoured in production) is
   *  forwarded to /api/cities too, so qa/registry-driven-client.mjs can stub a fake extra
   *  live city (see lib/fixtures.js's CITY_MANIFEST_FIXTURES) with zero client code change. */
  function networkUrl() {
    let fixture = "";
    try {
      fixture = new URLSearchParams(window.location.search).get("fixture") || "";
    } catch {
      fixture = "";
    }
    return fixture ? `${NETWORK_URL}?fixture=${encodeURIComponent(fixture)}` : NETWORK_URL;
  }

  const readyPromise = fetchJson(networkUrl())
    .then((data) => {
      if (applyManifest(data, "network")) {
        writeCache(data);
      }
      return manifest;
    })
    .catch(() => {
      if (source === "cache") {
        return manifest;
      }
      // No usable cache and the network fetch failed — fall back to the bundled seed
      // (a fresh install offline, or a very old APK's cache was cleared).
      return fetchJson(SEED_URL)
        .then((data) => {
          applyManifest(data, "seed");
          return manifest;
        })
        .catch(() => manifest);
    });

  function normalizeId(id) {
    return String(id || "").trim().toLowerCase();
  }

  function get(id) {
    const cityId = normalizeId(id);
    return manifest.cities.find((city) => city.id === cityId) || null;
  }

  /** Perth predates the manifest entirely and is always considered live, manifest or not. */
  function isLiveCity(id) {
    const cityId = normalizeId(id);
    return cityId === "perth" || Boolean(get(cityId));
  }

  function liveCityIds() {
    return manifest.cities.map((city) => city.id);
  }

  function countries() {
    return manifest.countries;
  }

  function boundsFor(id) {
    return get(id)?.bounds ?? null;
  }

  function isNearbyEligible(id) {
    return Boolean(get(id)?.nearbyEligible);
  }

  function directionsVersion(id) {
    return get(id)?.directionsVersion ?? null;
  }

  window.CityManifest = {
    ready: () => readyPromise,
    isLiveCity,
    liveCityIds,
    countries,
    boundsFor,
    isNearbyEligible,
    get,
    directionsVersion,
    _source: () => source,
  };
})();
