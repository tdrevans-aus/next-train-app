/**
 * Shared test helper for the Rotterdam/Amsterdam OVapi TripUpdates re-enable
 * (docs/jim-brief-nl-realtime-reenable.md). Builds an in-memory GTFS-RT
 * FeedMessage protobuf and stubs global.fetch so the two dogfood gates can
 * prove the live join (delay moves a row, cancellation removes one, a fetch
 * failure degrades to static) without any network access.
 */
import { zipSync, unzipSync } from "../../lib/vendor/fflate.mjs";
import GtfsRealtimeBindings from "../../lib/vendor/gtfs-realtime.mjs";
import { existsSync, readFileSync, readdirSync } from "fs";
import { join } from "path";

const ROOT = join(new URL("../..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"), "");

/**
 * Static GTFS bytes for a city's trimmed fixture. Prefers the local
 * qa/fixtures/<city>/gtfs/*.txt directory (regenerated by scripts/trim-*.mjs;
 * not committed for rotterdam/amsterdam) and otherwise fetches the published
 * Blob fixture zip the provider itself loads in production — so CI, which has
 * no local fixture directory, exercises the same bytes riders get. Must be
 * called BEFORE stubFetch() installs the fetch stub.
 */
export async function zipFixtureGtfs(city, staticUrl) {
  const gtfsDir = join(ROOT, "qa/fixtures", city, "gtfs");
  if (existsSync(gtfsDir)) {
    const files = readdirSync(gtfsDir).filter((name) => name.endsWith(".txt"));
    const zipInput = {};
    for (const name of files) {
      zipInput[name] = readFileSync(join(gtfsDir, name));
    }
    return Buffer.from(zipSync(zipInput, { level: 0 }));
  }
  if (!staticUrl) {
    throw new Error(`No local fixture at ${gtfsDir} and no staticUrl to fall back to`);
  }
  const response = await fetch(staticUrl, { headers: { "User-Agent": "next-train-qa" } });
  if (!response.ok) {
    throw new Error(`Fixture fallback fetch ${staticUrl} returned ${response.status}`);
  }
  return Buffer.from(await response.arrayBuffer());
}


/**
 * Pick real trips out of whichever static fixture the gate loaded (local dir or
 * the published Blob copy), so the gate never hardcodes trip ids from one
 * snapshot. Runs one static-only board fetch (RT stubbed to fail) on the first
 * service date the fixture serves, and returns the first two board rows.
 */
export async function discoverFixtureTrips({
  staticZip, staticUrl, rtUrl, fetchStationBoard, station, timeZone = "Europe/Amsterdam", hourLocal = "08:30:00",
}) {
  const files = unzipSync(new Uint8Array(staticZip));
  const cal = Buffer.from(files["calendar_dates.txt"] || files["calendar.txt"]).toString("utf8").split(String.fromCharCode(10)).map((l) => l.replace(new RegExp(String.fromCharCode(13) + "$"), ""));
  const header = cal[0].split(",");
  const dateCol = header.indexOf("date") >= 0 ? header.indexOf("date") : header.indexOf("start_date");
  const dates = cal.slice(1).map((l) => l.split(",")[dateCol]).filter((d) => /^\d{8}$/.test(d)).sort();
  if (!dates.length) throw new Error("fixture has no service dates");
  const ymd = dates[Math.floor(dates.length / 2)];
  const iso = `${ymd.slice(0, 4)}-${ymd.slice(4, 6)}-${ymd.slice(6, 8)}`;
  // Europe/Amsterdam is +02:00 (CEST) for every fixture date in Aug-Oct; +01:00 after the DST switch.
  const offset = new Date(`${iso}T12:00:00Z`) < new Date(`${ymd.slice(0, 4)}-10-25T01:00:00Z`) ? "+02:00" : "+01:00";
  const now = new Date(`${iso}T${hourLocal}${offset}`);
  const restore = stubFetch({ staticUrl, staticZip, rtUrl, rtFails: true });
  let board;
  try {
    board = await fetchStationBoard(station, { now });
  } finally {
    restore();
  }
  const [a, b] = board.trips;
  if (!a || !b || a.tripId === b.tripId) throw new Error(`fixture board at ${station} on ${iso} has fewer than two distinct trips`);
  const scheduledEpochSec = Math.floor(new Date(a.scheduledDeparture).getTime() / 1000);
  const clock = (d) => new Intl.DateTimeFormat("en-GB", { timeZone, hour: "2-digit", minute: "2-digit", hour12: false }).format(d);
  return {
    now,
    delayedTripId: a.tripId,
    cancelledTripId: b.tripId,
    stopId: a.stopId,
    scheduledEpochSec,
    delayedDisplayTime: (delaySec) => clock(new Date((scheduledEpochSec + delaySec) * 1000)),
  };
}

/**
 * @param {Array<{ tripId: string, stopId?: string, delaySec?: number, scheduledEpochSec?: number, cancelled?: boolean }>} updates
 */
export function encodeTripUpdates(updates) {
  const { transit_realtime: rt } = GtfsRealtimeBindings;
  const entities = updates.map((update, index) => {
    const tripUpdate = {
      trip: {
        tripId: update.tripId,
        scheduleRelationship: update.cancelled ? 3 : 0,
      },
    };
    if (update.delaySec != null && update.stopId) {
      // Mirror the real OVapi feed, which always carries an absolute time
      // alongside delay (protobufjs defaults an unset int64 `time` to 0,
      // which board.js would otherwise treat as a real epoch-0 arrival).
      const liveTime = Number(update.scheduledEpochSec ?? 0) + Number(update.delaySec);
      tripUpdate.stopTimeUpdate = [
        {
          stopId: update.stopId,
          arrival: { delay: update.delaySec, time: liveTime },
          departure: { delay: update.delaySec, time: liveTime },
        },
      ];
    }
    return rt.FeedEntity.create({ id: String(index + 1), tripUpdate });
  });
  const message = rt.FeedMessage.create({
    header: { gtfsRealtimeVersion: "2.0", incrementality: 0, timestamp: Math.floor(Date.now() / 1000) },
    entity: entities,
  });
  return Buffer.from(rt.FeedMessage.encode(message).finish());
}

/**
 * Installs a global.fetch stub that answers the static GTFS zip URL and the
 * RT TripUpdates URL from in-memory buffers, and returns a restore function.
 * @param {{ staticUrl: string, staticZip: Buffer, rtUrl: string, rtBuffer: Buffer | null, rtFails?: boolean }} options
 */
export function stubFetch({ staticUrl, staticZip, rtUrl, rtBuffer, rtFails = false, onRtFetch }) {
  const original = global.fetch;
  global.fetch = async (url, options = {}) => {
    const href = String(url);
    if (href === staticUrl) {
      return {
        ok: true,
        status: 200,
        headers: { get: () => null },
        arrayBuffer: async () => staticZip.buffer.slice(staticZip.byteOffset, staticZip.byteOffset + staticZip.byteLength),
      };
    }
    if (href === rtUrl) {
      onRtFetch?.();
      if (rtFails) {
        throw new Error("simulated OVapi RT fetch failure");
      }
      return {
        ok: true,
        status: 200,
        headers: { get: () => null },
        arrayBuffer: async () => rtBuffer.buffer.slice(rtBuffer.byteOffset, rtBuffer.byteOffset + rtBuffer.byteLength),
      };
    }
    return original(url, options);
  };
  return () => {
    global.fetch = original;
  };
}
