/** London TfL line names (chip = "<Line name> <Terminus>", no delimiter). */
const LONDON_LINES_PATH = join(ROOT, "qa/fixtures/uk-london-tfl/published-network.json");

function assert(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

function fold(value) {
  return String(value ?? "")
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

const DISAMBIGUATION_SUFFIX = /\s*\([^)]*\)\s*$/;

function stripParen(value) {
  return String(value ?? "").replace(DISAMBIGUATION_SUFFIX, "").trim();
}

/** Terminus a generic ("<Line> + <Terminus>" or bare "<Terminus>" or "<Terminus> (<Op>)") chip names. */
function genericChipTerminus(chip) {
  const stripped = stripParen(chip);
  const plusIdx = stripped.lastIndexOf(" + ");
  if (plusIdx !== -1) {
    return stripped.slice(plusIdx + 3).trim();
  }
  return stripped;
}

/**
 * Every folded identity a station may be self-referenced by: its own name, its aliases, and —
 * only when safe — its name with a trailing "(...)" disambiguation suffix stripped, so
 * "Richmond (London)" still matches a bare "Richmond" chip (the historical TfL bug, #linked
 * jim-brief-london-tfl-richmond-self-reference.md): that suffix exists only because another
 * city's catalog also has a "Richmond", so the stripped form is still the *same* physical stop.
 *
 * That stripping is unsafe when the same catalog already has a *different* real station whose
 * own exact name equals the stripped form — e.g. South Wales has both "Maesteg" and
 * "Maesteg (Ewenny Road)" as two distinct physical stops in the same town; there, a chip
 * "Maesteg (Transport for Wales)" on "Maesteg (Ewenny Road)" names the *other* real station,
 * not itself. `catalogNameSet` (every station's own exact folded name in this city) is the
 * disambiguator: only strip when nothing else in the catalog already owns that bare name.
 */
function selfKeysForStation(name, aliases = [], catalogNameSet = null) {
  const keys = new Set();
  const add = (value) => {
    const f = fold(value);
    if (f) keys.add(f);
  };
  add(name);
  for (const alias of aliases ?? []) {
    add(alias);
  }
  const ownFold = fold(name);
  const strippedFold = fold(stripParen(name));
  if (strippedFold && strippedFold !== ownFold) {
    if (!catalogNameSet || !catalogNameSet.has(strippedFold)) {
      keys.add(strippedFold);
    }
  }
  return keys;
}

function loadJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function loadCatalog(cityId) {
  const stationsPath = join(ROOT, "lib/cities", cityId, "stations.json");
  const stopsPath = join(ROOT, "lib/cities", cityId, "stops.json");
  const path = existsSync(stationsPath) ? stationsPath : existsSync(stopsPath) ? stopsPath : null;
  if (!path) {
    return [];
  }
  const raw = loadJson(path);
  if (Array.isArray(raw.stations)) return raw.stations;
  if (Array.isArray(raw.stops)) return raw.stops;
  if (Array.isArray(raw)) return raw;
  return [];
}

function catalogEntryByFoldedName(catalog) {
  const map = new Map();
  for (const entry of catalog) {
    const f = fold(entry.name);
    if (f && !map.has(f)) {
      map.set(f, entry);
    }
  }
  return map;
}

/** Every distinct station's own exact folded name in a city — see selfKeysForStation. */
function buildCatalogNameSet(catalog, extraKeys = []) {
  const set = new Set();
  for (const entry of catalog) {
    const f = fold(entry.name);
    if (f) set.add(f);
  }
  for (const key of extraKeys) {
    const f = fold(key);
    if (f) set.add(f);
  }
  return set;
}

/**
 * Checks one city's bundled `public/city-directions/<city>.json` for self-terminus chips using
 * the generic "<Line> + <Terminus>" / bare / "<Terminus> (<Op>)" parser. Returns violations.
 */
function checkBundledJson(cityId, catalog) {
  const jsonPath = join(ROOT, "public/city-directions", `${cityId}.json`);
  if (!existsSync(jsonPath)) {
    return { checked: 0, chips: 0, violations: [`missing public/city-directions/${cityId}.json`] };
  }
  const pack = loadJson(jsonPath);
  const byName = catalogEntryByFoldedName(catalog);
  const violations = [];
  let chipCount = 0;
  const stationNames = Object.keys(pack);
  // Use the bundled JSON's own key set as the distinctness signal too (not just the catalog),
  // since the JSON is the actual shipped station list and is what a Maesteg-style same-town
  // collision would show up in.
  const catalogNameSet = buildCatalogNameSet(catalog, stationNames);

  const exemptChips = KNOWN_EXEMPT_CHIPS[cityId] ?? null;

  for (const stationKey of stationNames) {
    const chips = Array.isArray(pack[stationKey]) ? pack[stationKey] : [];
    const catalogEntry = byName.get(fold(stationKey));
    const selfKeys = selfKeysForStation(stationKey, catalogEntry?.aliases, catalogNameSet);
    for (const chip of chips) {
      chipCount += 1;
      if (exemptChips?.has(chip)) {
        continue;
      }
      const terminusKey = fold(genericChipTerminus(chip));
      if (terminusKey && selfKeys.has(terminusKey)) {
        violations.push(`${cityId} bundled: station "${stationKey}" offers self chip "${chip}"`);
      }
    }
  }
  return { checked: stationNames.length, chips: chipCount, violations };
}

/** Same generic check, but calling the city's live-derived helper directly for every catalog station. */
async function checkLiveHelper(cityId, catalog, modulePath) {
  const violations = [];
  let checked = 0;
  let chipCount = 0;
  if (catalog.length === 0) {
    return { checked, chips: chipCount, violations, skipped: "no catalog file" };
  }
  const mod = await import(modulePath);
  const marketingLabelsForStation = mod.marketingLabelsForStation;
  if (typeof marketingLabelsForStation !== "function") {
    return { checked, chips: chipCount, violations, skipped: "no marketingLabelsForStation export" };
  }
  const catalogNameSet = buildCatalogNameSet(catalog);
  for (const station of catalog) {
    checked += 1;
    const selfKeys = selfKeysForStation(station.name, station.aliases, catalogNameSet);
    let labels = [];
    try {
      labels = marketingLabelsForStation(station.name) ?? [];
    } catch (err) {
      violations.push(`${cityId} live-helper: marketingLabelsForStation("${station.name}") threw: ${err.message}`);
      continue;
    }
    for (const chip of labels) {
      chipCount += 1;
      const terminusKey = fold(genericChipTerminus(chip));
      if (terminusKey && selfKeys.has(terminusKey)) {
        violations.push(`${cityId} live-helper: station "${station.name}" offers self chip "${chip}"`);
      }
    }
  }
  return { checked, chips: chipCount, violations };
}

/** London's chip format glues the line name straight onto the terminus with no delimiter
 * ("District Richmond") — strip a known line-name prefix instead of guessing a delimiter. */
async function checkLondonLiveHelper(catalog) {
  const violations = [];
  let checked = 0;
  let chipCount = 0;
  const published = loadJson(LONDON_LINES_PATH);
  const lineNames = (published.lines ?? [])
    .map((l) => String(l.name || "").trim())
    .filter(Boolean)
    .sort((a, b) => b.length - a.length);
  const mod = await import("../lib/cities/uk-london-tfl/marketing-directions.js");
  const catalogNameSet = buildCatalogNameSet(catalog);
  for (const station of catalog) {
    checked += 1;
    const selfKeys = selfKeysForStation(station.name, station.aliases, catalogNameSet);
    let labels = [];
    try {
      labels = mod.marketingLabelsForStation(station.name) ?? [];
    } catch (err) {
      violations.push(`uk-london-tfl live-helper: marketingLabelsForStation("${station.name}") threw: ${err.message}`);
      continue;
    }
    for (const chip of labels) {
      chipCount += 1;
      const stripped = stripParen(chip);
      const matchedLine = lineNames.find((name) => stripped === name || stripped.startsWith(`${name} `));
      const terminus = matchedLine
        ? stripped === matchedLine
          ? "" // loop chip (line name only, e.g. "Circle") — no terminus to check
          : stripped.slice(matchedLine.length).trim()
        : stripped;
      const terminusKey = fold(terminus);
      if (terminusKey && selfKeys.has(terminusKey)) {
        violations.push(`uk-london-tfl live-helper: station "${station.name}" offers self chip "${chip}"`);
      }
    }
  }
  return { checked, chips: chipCount, violations };
}

/** Perth has no bundled JSON — check its static line-map directions module directly. */
async function checkPerth() {
  const mod = await import("../lib/cities/perth/static-directions.js");
  const lineMap = mod.getPerthLineMap();
  const violations = [];
  let checked = 0;
  let chipCount = 0;
  const seen = new Set();
  const allStationNames = new Set();
  for (const line of lineMap.lines ?? []) {
    for (const stationName of line.stations ?? []) {
      allStationNames.add(stationName);
    }
  }
  const catalogNameSet = buildCatalogNameSet([], allStationNames);
  for (const line of lineMap.lines ?? []) {
    for (const stationName of line.stations ?? []) {
      const key = fold(stationName);
      if (seen.has(key)) continue;
      seen.add(key);
      checked += 1;
      const selfKeys = selfKeysForStation(stationName, [], catalogNameSet);
      const labels = mod.staticDirectionsForStation(stationName) ?? [];
      for (const chip of labels) {
        chipCount += 1;
        const terminusKey = fold(genericChipTerminus(chip));
        if (terminusKey && selfKeys.has(terminusKey)) {
          violations.push(`perth: station "${stationName}" offers self chip "${chip}"`);
        }
      }
    }
  }
  return { checked, chips: chipCount, violations };
}

async function main() {
  const rows = [];
  let anyViolation = false;

  const liveCities = CITIES.filter((c) => c.status === "live");

  for (const city of liveCities) {
    const cityId = city.id;

    if (EXCLUDED[cityId]) {
      rows.push({ cityId, verdict: "SKIP", detail: EXCLUDED[cityId] });
      continue;
    }

    if (cityId === "perth") {
      const result = await checkPerth();
      const ok = result.violations.length === 0;
      anyViolation = anyViolation || !ok;
      rows.push({
        cityId,
        verdict: ok ? "PASS" : "FAIL",
        detail: `static-directions: ${result.checked} stations, ${result.chips} chips${
          result.violations.length ? " — " + result.violations.join("; ") : ""
        }`,
      });
      continue;
    }

    const catalog = loadCatalog(cityId);
    const bundled = checkBundledJson(cityId, catalog);
    const methods = [`bundled (${bundled.checked} stations, ${bundled.chips} chips)`];
    const violations = [...bundled.violations];

    if (cityId === "uk-london-tfl") {
      const live = await checkLondonLiveHelper(catalog);
      methods.push(`live-helper (${live.checked} stations, ${live.chips} chips)`);
      violations.push(...live.violations);
    } else if (LIVE_HELPER_MODULES[cityId]) {
      const live = await checkLiveHelper(cityId, catalog, LIVE_HELPER_MODULES[cityId]);
      if (live.skipped) {
        methods.push(`live-helper skipped (${live.skipped})`);
      } else {
        methods.push(`live-helper (${live.checked} stations, ${live.chips} chips)`);
      }
      violations.push(...live.violations);
    }

    const ok = violations.length === 0;
    anyViolation = anyViolation || !ok;
    rows.push({
      cityId,
      verdict: ok ? "PASS" : "FAIL",
      detail: `${methods.join(", ")}${violations.length ? " — " + violations.join("; ") : ""}`,
    });
  }

  const idWidth = Math.max(...rows.map((r) => r.cityId.length), 4);
  console.log("no-self-terminus-gate — per-city results:");
  for (const row of rows) {
    console.log(`  ${row.cityId.padEnd(idWidth)}  ${row.verdict.padEnd(4)}  ${row.detail}`);
  }

  const passCount = rows.filter((r) => r.verdict === "PASS").length;
  const skipCount = rows.filter((r) => r.verdict === "SKIP").length;
  const failCount = rows.filter((r) => r.verdict === "FAIL").length;
  console.log(
    `no-self-terminus-gate: ${passCount} pass, ${skipCount} skipped, ${failCount} failed (of ${rows.length} live cities)`
  );

  assert(!anyViolation, "one or more live cities offer a station a chip naming itself — see FAIL rows above");
  console.log("no-self-terminus-gate: ok");
}

main().catch((err) => {
  console.error(err.stack || err.message);
  process.exit(1);
});
