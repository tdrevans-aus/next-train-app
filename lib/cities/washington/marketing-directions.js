/**
 * Washington, D.C. (WMATA Metrorail) — hub lock, doNotGroup/doNotCollapse guards, and the
 * direction model for the shared Blue/Orange/Silver trunk.
 *
 * Hub lock: Metro Center (Red × Orange/Blue/Silver transfer). This is a through-cross, not a
 * single-end hub — Red runs NW–NE, Orange/Blue/Silver run E–W — so "to Metro Center"/"to City"
 * must never appear as a direction chip; directions are always the suburban terminus. Metro
 * Center is ONE catalog station (both platform codes A01+C01 are queried together at request
 * time in lib/providers/washington.js — never split into two catalog entries; this is a
 * combined-board rider concept, same shape as Chicago/Adelaide's shared hub boards).
 *
 * doNotCollapse (docs/washington-d1/hazard-pack.md H1/H4/H6, published-network.json
 * printedInnerCityNames): Metro Center vs Gallery Place-Chinatown (one stop apart, different
 * transfers — NOT the same station); Farragut North (Red only) vs Farragut West
 * (Orange/Blue/Silver only) — two separate stations, two separate streets; Union Station /
 * L'Enfant Plaza / Federal Triangle / McPherson Sq are real, separately-catalogued stations that
 * must never stand in for the Metro Center hub identity. No same-printed-name-different-place
 * families exist on this map (hazard-pack.md H5: "no official nested codes... six passenger
 * colors only") — unlike Chicago/BART, resolveCatalogEntry() here never throws an
 * ambiguous-name error, since D1 has no colliding station names to disambiguate.
 *
 * ## Correction, 27 Sep 2026 (docs/jim-brief-washington-one-train-per-direction.md)
 *
 * The original "Line + terminus" model (`Red Line + Glenmont`, `Silver Line + Ashburn`) is
 * RETIRED — direction chips are now **terminus-only** (Perth/Melbourne/Adelaide/Boston style,
 * PR #439/#440): `New Carrollton`, `Vienna/Fairfax-GMU`, `Franconia-Springfield`,
 * `Downtown Largo`, `Ashburn`, `Shady Grove`, `Glenmont`, `Greenbelt`, `Branch Av`, `Huntington`,
 * `Wiehle-Reston East`.
 *
 * Root cause: WMATA's Real-Time Rail Predictions API returns the next ~3 trains PER PLATFORM
 * GROUP, not per line. On the shared Blue/Orange/Silver trunk those three are interleaved across
 * lines sharing the same platform, so a "Line + terminus" chip only ever matched the one line's
 * own trains to that terminus — a rider bound for New Carrollton saw at most the Orange-only or
 * Silver-only train, never both, even though WMATA's own raw payload carried both. Confirmed live
 * 27 Sep 2026, ~09:15 EDT (Sunday service): raw GetPrediction at Metro Center for New Carrollton
 * carried both an Orange- and a Silver-line train inside the same 09:00-09:10 window; the old
 * model showed "Orange Line + New Carrollton" = 0 upcoming and "Silver Line + New Carrollton" = 1
 * upcoming (never both together as "New Carrollton" = 2). Red/Green never showed this because
 * neither shares a platform group with another line at any D1 station.
 *
 * Every train whose (abbreviation-normalized) DestinationName resolves to a terminus in
 * `LINE_TERMINI[lineId]` now gets that BARE terminus as its `destination` — regardless of line —
 * so `tripMatchesMarketingChip` matches every line's trains to that terminus, not just one line's.
 * Each trip still carries its own `lineId`/`line` (bare colour word, e.g. "Silver") and a
 * `printedDestination` of `"{Label} Line · {terminus}"` (e.g. "Silver Line · New Carrollton") so a
 * board row can still show which physical line that particular train runs on even though the
 * chip itself is line-agnostic — see printedLineTerminusLabel() below and
 * lib/providers/washington.js's mapWmataTrainToTrip.
 *
 * Two short-turns are added to `LINE_TERMINI` as first-class terminus chips per the D1 pack:
 * Blue's genuine "Huntington" short-turn (confirmed live 20 Sep 2026, previously only handled by
 * the bare-line-label fallback) and Silver's "Wiehle-Reston East" short-turn (hazard-pack.md
 * "Ashburn vs Wiehle-Reston East"; Wiehle-Reston East is a through stop on Silver's full-length
 * run to Ashburn, but WMATA does short-turn some Silver trains there).
 *
 * Every retired "<Line> Line + <terminus>" label ships a server-side legacy alias (PR #440
 * mechanism — lib/cities/washington/direction-label-aliases.json, generated by
 * scripts/generate-direction-label-aliases.mjs) so saved routes on installed clients keep
 * resolving to the new bare-terminus chip.
 *
 * @see docs/washington-d1/direction-model-memo.md
 * @see docs/washington-d1/hazard-pack.md
 * @see docs/washington-d1/oracle-clash-report.md
 * @see docs/jim-brief-washington-one-train-per-direction.md
 */

